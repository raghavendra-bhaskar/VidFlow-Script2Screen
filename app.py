def _validate_muxed_media(path: Path):
    """Do not report a mux as complete unless it contains playable video and audio."""
    if not path.is_file() or path.stat().st_size == 0:
        raise RuntimeError("FFmpeg did not create an output video.")
    for stream_type in ("v:0", "a:0"):
        stream = run([
            FFPROBE, "-v", "error", "-select_streams", stream_type,
            "-show_entries", "stream=codec_type", "-of", "csv=p=0", str(path),
        ])
        if not stream:
            raise RuntimeError(f"The output video is missing its {stream_type[0]} stream.")


def _probe_duration(path: Path) -> float:
    """Robustly probe a video/audio file duration in seconds.

    Browser-recorded WebM files from Chrome MediaRecorder often have no duration
    in the container header.  This helper tries three strategies:

    1. JSON probe — reads format + all stream headers + stream tags in one call.
       Catches format duration, per-stream duration, and the DURATION tag that
       Chrome writes in HH:MM:SS format even when the container header is absent.
    2. FFmpeg copy-remux — copies all packets without re-encoding; FFmpeg must
       seek through the whole file to write the output, so the output container
       gets a proper duration.  Only the remuxed file is probed; the original is
       unchanged.
    3. Hard error with a user-friendly message.
    """
    import json as _j

    def _pos_float(s):
        """Return float(s) if s is a positive number, else None."""
        try:
            f = float(s)
            return f if f > 0 else None
        except (TypeError, ValueError):
            return None

    # ── Strategy 1: comprehensive JSON probe ────────────────────────────────────
    try:
        r = subprocess.run(
            [FFPROBE, "-v", "quiet", "-print_format", "json",
             "-show_streams", "-show_format", str(path)],
            capture_output=True, text=True
        )
        if r.returncode == 0:
            data = _j.loads(r.stdout)
            # a) Format-level duration
            v = _pos_float(data.get("format", {}).get("duration", "N/A"))
            if v:
                return v
            # b) Per-stream duration + DURATION tag (all streams, all tag spellings)
            for stream in data.get("streams", []):
                v = _pos_float(stream.get("duration", "N/A"))
                if v:
                    return v
                tags = stream.get("tags", {})
                for key in ("DURATION", "duration", "Duration"):
                    tag_val = str(tags.get(key, ""))
                    if ":" in tag_val:  # HH:MM:SS.mmm format
                        try:
                            h, m, s = tag_val.split(":")
                            d = float(h) * 3600 + float(m) * 60 + float(s)
                            if d > 0:
                                return d
                        except (ValueError, AttributeError):
                            pass
    except Exception:
        pass

    # ── Strategy 2: FFmpeg copy-remux ─────────────────────────────────────────
    _remux = path.with_name(path.stem + "__dur_fix.mkv")
    try:
        r = subprocess.run(
            [FFMPEG, "-y", "-i", str(path), "-c", "copy", str(_remux)],
            capture_output=True
        )
        if r.returncode == 0 and _remux.exists() and _remux.stat().st_size > 0:
            r2 = subprocess.run(
                [FFPROBE, "-v", "error", "-show_entries", "format=duration",
                 "-of", "default=noprint_wrappers=1:nokey=1", str(_remux)],
                capture_output=True, text=True
            )
            v = _pos_float(r2.stdout.strip())
            if v:
                return v
    except Exception:
        pass
    finally:
        if _remux.exists():
            _remux.unlink(missing_ok=True)

    raise ValueError(
        f"Cannot determine duration of '{path.name}'. Check that it plays in the preview; "
        "renaming a WebM recording to .mp3 does not convert it. Use the Convert to MP3 button "
        "in Self voice dubbing and upload the converted file."
    )

