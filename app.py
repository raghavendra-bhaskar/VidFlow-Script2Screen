def image_to_clip(image_path, clip_path, seconds):
    """Convert a still image to a video clip with a slow Ken-Burns zoom effect.

    The zoompan filter incrementally increases the zoom by 0.07% per frame up to
    a maximum of 107% — a subtle motion that keeps single-image scenes from
    feeling static without distracting from the narration.
    The clip has no audio track (-an); narration is added later in build_final_ffmpeg_command().
    """
    w, h = dims()
    frames = max(48, int(seconds*24))
    vf = (f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},"
          f"zoompan=z='min(zoom+0.0007,1.07)':d={frames}:s={w}x{h}:fps=24,"
          "setsar=1,format=yuv420p")
    run([FFMPEG, "-y", "-loop", "1", "-i", str(image_path), "-vf", vf,
         "-t", f"{seconds:.3f}", "-r", "24", "-an", "-c:v", "libx264",
         "-preset", "veryfast", "-pix_fmt", "yuv420p", str(clip_path)])

def normalize_stock_clip(source, output, seconds):
    """Re-encode a Pexels stock clip to the target resolution and duration.

    Trims to the per-sentence duration, scales + crops to fill the canvas,
    and strips audio so all clips have a uniform silent video-only track.
    The narration audio is mixed in by build_final_ffmpeg_command().
    """
    w, h = dims()
    run([FFMPEG, "-y", "-i", str(source), "-t", f"{seconds:.3f}",
         "-vf", f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps=24,setsar=1",
         "-an", "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
         str(output)])

