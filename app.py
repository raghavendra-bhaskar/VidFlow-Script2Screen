def run(cmd):
    """Run an external command (FFmpeg, ffprobe) and raise on failure.

    stderr is truncated to the last 2500 characters so that Streamlit's
    error box stays readable — FFmpeg can emit thousands of lines of
    progress output before the actual error message at the end.
    """
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode:
        raise RuntimeError(p.stderr[-2500:] or "Command failed")
    return p.stdout.strip()


def _probe_duration(path: Path) -> float:
    """Robustly probe a video/audio file duration in seconds.

    Browser-recorded WebM files from Chrome MediaRecorder often have no duration
    in the container header.  This helper tries three strategies:

    1. JSON probe — reads format + all stream headers + stream tags in one call.
       Catches format duration, per-stream duration, and the DURATION tag that
       Chrome writes in HH:MM:SS format even when the container header is absent.
    2. FFmpeg copy-remux — copies all packets without re-encoding; FFmpeg must
       seek through the whole file to write the output, so the output container
       gets a proper duration.  Only the remuxed file is probed; the original is
       unchanged.
    3. Hard error with a user-friendly message.
    """
    import json as _j

    def _pos_float(s):
        """Return float(s) if s is a positive number, else None."""
        try:
            f = float(s)
            return f if f > 0 else None
        except (TypeError, ValueError):
            return None

    # ── Strategy 1: comprehensive JSON probe ────────────────────────────────────
    try:
        r = subprocess.run(
            [FFPROBE, "-v", "quiet", "-print_format", "json",
             "-show_streams", "-show_format", str(path)],
            capture_output=True, text=True
        )
        if r.returncode == 0:
            data = _j.loads(r.stdout)
            # a) Format-level duration
            v = _pos_float(data.get("format", {}).get("duration", "N/A"))
            if v:
                return v
            # b) Per-stream duration + DURATION tag (all streams, all tag spellings)
            for stream in data.get("streams", []):
                v = _pos_float(stream.get("duration", "N/A"))
                if v:
                    return v
                tags = stream.get("tags", {})
                for key in ("DURATION", "duration", "Duration"):
                    tag_val = str(tags.get(key, ""))
                    if ":" in tag_val:  # HH:MM:SS.mmm format
                        try:
                            h, m, s = tag_val.split(":")
                            d = float(h) * 3600 + float(m) * 60 + float(s)
                            if d > 0:
                                return d
                        except (ValueError, AttributeError):
                            pass
    except Exception:
        pass

    # ── Strategy 2: FFmpeg copy-remux ─────────────────────────────────────────
    _remux = path.with_name(path.stem + "__dur_fix" + path.suffix)
    try:
        r = subprocess.run(
            [FFMPEG, "-y", "-i", str(path), "-c", "copy", str(_remux)],
            capture_output=True
        )
        if r.returncode == 0 and _remux.exists() and _remux.stat().st_size > 0:
            r2 = subprocess.run(
                [FFPROBE, "-v", "error", "-show_entries", "format=duration",
                 "-of", "default=noprint_wrappers=1:nokey=1", str(_remux)],
                capture_output=True, text=True
            )
            v = _pos_float(r2.stdout.strip())
            if v:
                return v
    except Exception:
        pass
    finally:
        if _remux.exists():
            _remux.unlink(missing_ok=True)

    raise ValueError(
        f"Cannot determine duration of '{path.name}'.  "
        "For browser-recorded WebM files, open in VLC → Media → Convert/Save → "
        "choose MP4 profile → save, then re-upload the MP4."
    )

def dims():
    return (1280, 720) if aspect == "16:9 landscape" else (720, 1280)

def generate_ai_image(client, prompt, path):
    """Generate one scene image from a sentence prompt using the Gemini image model.

    The raw Gemini image may be any resolution.  We thumbnail-scale it to fit inside
    the target canvas (1280×720 or 720×1280) preserving aspect ratio, then paste it
    centred on a dark navy background so no black letterbox edge is visible.
    Model name comes from GEMINI_IMAGE_MODEL env var so it can be updated without
    a code change when Gemini releases newer image models.
    """
    model = os.getenv("GEMINI_IMAGE_MODEL", "gemini-2.5-flash-image")
    result = client.models.generate_content(
        model=model, contents=prompt,
        config=types.GenerateContentConfig(response_modalities=["IMAGE", "TEXT"])
    )
    for part in result.candidates[0].content.parts:
        if getattr(part, "inline_data", None) is not None:
            image = Image.open(part.as_image()).convert("RGB")
            w, h = dims()
            image.thumbnail((w, h), Image.Resampling.LANCZOS)
            canvas = Image.new("RGB", (w, h), (12, 18, 32))
            canvas.paste(image, ((w-image.width)//2, (h-image.height)//2))
            canvas.save(path, quality=92)
            return
    raise RuntimeError("Gemini returned no image. Verify model access and quota.")

def stock_video(client_key, query, path):
    """Download the best-matching Pexels stock clip for a sentence keyword.

    The Pexels API returns up to 8 results per query.  We pick the first result
    (highest relevance) and then choose the MP4 rendition whose width is closest
    to the target canvas width (1280 for landscape, 720 for portrait) to minimise
    the amount of re-scaling done by normalize_stock_clip().
    The source URL is returned so it can be credited in the UI.
    """
    if not client_key:
        raise RuntimeError("Add PEXELS_API_KEY to .env to use Stock footage.")
    r = requests.get(
        "https://api.pexels.com/v1/videos/search",
        headers={"Authorization": client_key},
        params={"query": query, "per_page": 8, "orientation": "landscape" if aspect.startswith("16") else "portrait"},
        timeout=30
    )
    r.raise_for_status()
    videos = r.json().get("videos", [])
    if not videos:
        raise RuntimeError(f"No Pexels clips found for: {query}")
    video_files = sorted(videos[0].get("video_files", []), key=lambda x: x.get("width", 0))
    choices = [v for v in video_files if v.get("file_type") == "video/mp4" and v.get("link")]
    if not choices:
        raise RuntimeError("Pexels returned no downloadable MP4.")
    target_w = 1280 if aspect.startswith("16") else 720
    chosen = min(choices, key=lambda x: abs((x.get("width") or target_w)-target_w))
    data = requests.get(chosen["link"], timeout=90)
    data.raise_for_status()
    Path(path).write_bytes(data.content)
    return videos[0].get("url", "https://www.pexels.com")

def make_explainer_card(text, path, index):
    """Draw a dark-themed animated explainer title card using Pillow only.

    Produces a visually consistent 1280×720 (or 720×1280) scene without any
    external API calls.  Two concentric ellipses and two horizontal rules
    create the "technology explainer" look; the sentence is word-wrapped into
    the left column.  Falls back to Pillow's built-in bitmap font when
    DejaVuSans.ttf is not installed on the host OS.
    """
    w, h = dims()
    image = Image.new("RGB", (w, h), (13, 24, 48))
    d = ImageDraw.Draw(image)
    # Abstract technology explainer graphics; no image API required.
    d.ellipse((w*0.58, h*0.12, w*0.94, h*0.60), outline=(55, 190, 210), width=8)
    d.ellipse((w*0.66, h*0.20, w*0.86, h*0.48), outline=(245, 190, 80), width=6)
    d.line((w*0.60, h*0.64, w*0.90, h*0.64), fill=(55,190,210), width=5)
    d.line((w*0.66, h*0.70, w*0.84, h*0.70), fill=(245,190,80), width=5)
    try:
        font = ImageFont.truetype("DejaVuSans.ttf", max(24, int(w/28)))
        small = ImageFont.truetype("DejaVuSans.ttf", max(16, int(w/48)))
    except OSError:
        font, small = ImageFont.load_default(), ImageFont.load_default()
    d.text((w*0.07, h*0.14), f"IDEA {index+1:02d}", font=small, fill=(245,190,80))
    words = textwrap.wrap(text, width=25 if w < h else 36)
    y = int(h*0.28)
    for line in words[:5]:
        d.text((w*0.07, y), line, font=font, fill="white")
        y += int(h*0.075)
    d.text((w*0.07, h*0.83), "TEXT TO VIDEO AI", font=small, fill=(120,210,225))
    image.save(path, quality=92)

def image_to_clip(image_path, clip_path, seconds):
    """Convert a still image to a video clip with a slow Ken-Burns zoom effect.

    The zoompan filter incrementally increases the zoom by 0.07% per frame up to
    a maximum of 107% — a subtle motion that keeps single-image scenes from
    feeling static without distracting from the narration.
    The clip has no audio track (-an); narration is added later in build_final_ffmpeg_command().
    """
    w, h = dims()
    frames = max(48, int(seconds*24))
    vf = (f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},"
          f"zoompan=z='min(zoom+0.0007,1.07)':d={frames}:s={w}x{h}:fps=24,"
          "setsar=1,format=yuv420p")
    run([FFMPEG, "-y", "-loop", "1", "-i", str(image_path), "-vf", vf,
         "-t", f"{seconds:.3f}", "-r", "24", "-an", "-c:v", "libx264",
         "-preset", "veryfast", "-pix_fmt", "yuv420p", str(clip_path)])

def normalize_stock_clip(source, output, seconds):
    """Re-encode a Pexels stock clip to the target resolution and duration.

    Trims to the per-sentence duration, scales + crops to fill the canvas,
    and strips audio so all clips have a uniform silent video-only track.
    The narration audio is mixed in by build_final_ffmpeg_command().
    """
    w, h = dims()
    run([FFMPEG, "-y", "-i", str(source), "-t", f"{seconds:.3f}",
         "-vf", f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps=24,setsar=1",
         "-an", "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
         str(output)])

