@st.cache_resource
def _get_server_state():
    """Return a single mutable dict that persists for the lifetime of the Streamlit process.
    Used to share recordings_dir, uploads_dir, and trim state between the HTTP handler
    and Streamlit UI code across all reruns (including hot-reloads).
    """
    return {"recordings_dir": "", "uploads_dir": "", "trim": {}, "started": False}


def _ensure_servers(recordings_dir: str, uploads_dir: str):
    """Start the local HTTP server on port 8502 (idempotent).

    Endpoints
    ---------
    POST /             : Accept screen-recording blob; save to recordings_dir.
    GET  /v/<filename> : Serve a video file from uploads_dir (for the in-browser trim player).
    POST /trim         : Accept {clip_idx, start, end} JSON; persist to shared state dict.
    GET  /trim         : Return full trim state as JSON.
    OPTIONS *          : CORS preflight.
    """
    import json as _json
    state = _get_server_state()
    state["recordings_dir"] = recordings_dir
    state["uploads_dir"] = uploads_dir

    if state["started"]:
        return state  # server is already running

    class _Handler(BaseHTTPRequestHandler):
        def log_message(self, fmt, *args):
            pass  # silence access log

        def _cors(self):
            self.send_header("Access-Control-Allow-Origin", "*")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
            self.send_header("Access-Control-Allow-Headers",
                             "Content-Type, X-Filename, X-Clip-Idx")

        def do_OPTIONS(self):
            self.send_response(204)
            self._cors()
            self.end_headers()

        def do_GET(self):
            if self.path.startswith("/v/"):
                filename = self.path[3:]
                video_path = Path(state["uploads_dir"]) / filename
                if video_path.exists():
                    ext = video_path.suffix.lower()
                    ct = {".mp4": "video/mp4", ".webm": "video/webm",
                          ".mov": "video/quicktime", ".mkv": "video/x-matroska"}.get(ext, "video/mp4")
                    data = video_path.read_bytes()
                    self.send_response(200)
                    self._cors()
                    self.send_header("Content-Type", ct)
                    self.send_header("Content-Length", str(len(data)))
                    self.send_header("Accept-Ranges", "bytes")
                    self.end_headers()
                    self.wfile.write(data)
                else:
                    self.send_response(404)
                    self._cors()
                    self.end_headers()
            elif self.path == "/trim":
                body = _json.dumps(state["trim"]).encode()
                self.send_response(200)
                self._cors()
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            else:
                self.send_response(404)
                self._cors()
                self.end_headers()

        def do_POST(self):
            length = int(self.headers.get("Content-Length", 0))
            raw = self.rfile.read(length)
            if self.path == "/trim":
                data = _json.loads(raw.decode())
                state["trim"][str(data["clip_idx"])] = {
                    "start": float(data["start"]),
                    "end": float(data["end"]),
                }
                self.send_response(200)
                self._cors()
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(b'{"ok":true}')
            else:
                # Screen recording blob upload
                filename = self.headers.get(
                    "X-Filename",
                    f"recording_{datetime.now().strftime('%Y%m%d_%H%M%S')}.webm"
                )
                save_path = Path(state["recordings_dir"]) / filename
                save_path.write_bytes(raw)
                self.send_response(200)
                self._cors()
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(f'{{"saved":"{save_path.name}"}}'.encode())

    try:
        server = HTTPServer(("localhost", 8502), _Handler)
        t = threading.Thread(target=server.serve_forever, daemon=True)
        t.start()
        state["started"] = True
    except OSError:
        state["started"] = True  # port already in use — old server still running
    return state


