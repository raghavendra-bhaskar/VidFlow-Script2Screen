"""app.py — VidFlow: Script to Screen  (Streamlit web UI)

Seven tabs
----------
Tab 1  Generate from script
    Script text → TTS narration → per-sentence scene images/clips → subtitle SRT → final MP4.
    Four video styles: Animated explainer (offline), AI-generated scenes (Gemini),
    Stock footage (Pexels), Talking AI presenter (placeholder).

Tab 2  Upload video + narrate
    Multi-segment timeline editor: upload a video, add narration segments at exact timestamps.
    Each segment is individually synthesised; 2-pass rate-matching fits speech to a time window.
    Uses FFmpeg adelay + amix + apad to place audio without overlap and extend if needed.

Tab 3  Video editor  (7 sub-tabs)
    Trim   — drag-handle timeline (served by a local HTTP server on port 8502) + number inputs.
             FFmpeg re-encodes trimmed clips; saved to trimmed_videos/.
    Merge  — concatenate clips in a user-defined order via FFmpeg concat demuxer.
             Saved to merged_videos/; results persisted in session_state for rerun safety.
    A/V Sync — replace or mix audio at a configurable offset; pad/extend video if audio is longer.
             Saved to video+narrated/; results persisted in session_state.
    Self voice dubbing — browser microphone recording used to replace or mix the video's soundtrack.
    URL video trim — import a public direct-download video URL and save a trimmed MP4.
    Voice + webcam — record camera + microphone and overlay the recording in the lower-right corner.
    Video overlay — place one uploaded video over another with configurable size and position.

Tab 4  Transcript
    faster-whisper offline ASR converts any video/audio to timestamped text.
    Download as plain .txt or .srt subtitle file.

Tab 5  Screen recorder
    Browser MediaRecorder (VP9/WebM) captures screen + optional microphone.
    Recordings are saved to screen_recordings/ with timestamp filenames.

Tab 6  Auto-narrate from video
    Extracts evenly-spaced JPEG frames via FFmpeg, then sends them to either:
      • Gemini vision API (cloud, requires GOOGLE_API_KEY)
      • Local Ollama server (offline, requires a vision model: llava / moondream / bakllava)
    Generated narration script is editable and can be fed into Tab 1.

Tab 7  Audio editor  (3 sub-tabs)
    Text → Audio — standalone TTS tab with live word-count + duration estimate.
                   Each file auto-saved with incremental name (audio_001.mp3 …).
    Trim audio   — trim any audio file; saved to audio_edits/.
    Merge audio  — concatenate audio files in order; saved to audio_edits/.

Session-state persistence
--------------------------
Downstream outputs (TTS bytes, merged video, A/V sync result, etc.) are stored in
st.session_state so that download and save buttons remain visible across Streamlit reruns
(a rerun happens every time any widget is clicked).

FFmpeg resolution
-----------------
video_core._locate_bin() finds ffmpeg/ffprobe via the Windows registry even when the
Streamlit process inherited a stale PATH (e.g. FFmpeg installed via winget after app start).

HTTPS
-----
Streamlit is configured in .streamlit/config.toml to use cert.pem + key.pem generated by
gen_cert.py (self-signed, 10-year, localhost/127.0.0.1). Access via https://localhost:8501.

Offline TTS voice selection
----------------------------
When GOOGLE_APPLICATION_CREDENTIALS is not set, list_offline_voices() enumerates all
installed pyttsx3 system voices so the user can switch between them from the sidebar.
"""

