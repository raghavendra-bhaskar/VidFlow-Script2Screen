                            for seg in segs:
                                text = seg.text.strip()
                                words = text.rstrip(".,!?").lower().split()
                                if not text or (len(words) <= 1 and words and words[0] in _FILLERS):
                                    prev_end = seg.end
                                    continue
                                if current and (seg.start - prev_end > pause_gap
                                                or len(current) >= max_per_para):
                                    paras.append(" ".join(current))
                                    current = []
                                current.append(text)
                                prev_end = seg.end
                            if current:
                                paras.append(" ".join(current))
                            return "\n\n".join(paras)

